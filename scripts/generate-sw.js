// Writes dist/sw.js after `expo export -p web`. Run via `npm run build:web`.
/* global __dirname */
//
// Caching strategy:
// - Page loads (navigations): network first, so every launch while online
//   gets the latest deploy; the cached page is only a fallback offline.
// - Hashed build output (_expo/static, assets/): cache first. Their filenames
//   change whenever their contents do, so a cached copy is never stale.
// - Everything else same-origin (manifest, icons): stale-while-revalidate.
// Cross-origin requests (Supabase, Discogs images, Google) are not touched.
//
// Each build gets a unique BUILD_ID, which changes sw.js byte-for-byte so the
// browser installs the new worker, and namespaces the cache so the old one is
// deleted on activation.
const fs = require('fs');
const path = require('path');

const DIST = path.join(__dirname, '..', 'dist');

function listFiles(dir) {
  const abs = path.join(DIST, dir);
  if (!fs.existsSync(abs)) return [];
  return fs.readdirSync(abs).map((f) => `${dir}/${f}`);
}

if (!fs.existsSync(path.join(DIST, 'index.html'))) {
  console.error('dist/index.html not found: run `expo export -p web` first');
  process.exit(1);
}

const buildId = (process.env.GITHUB_SHA || '').slice(0, 12) || Date.now().toString(36);

// App shell, precached on install so the app opens offline straight away.
const precache = [
  '',
  'manifest.json',
  'favicon.ico',
  'icon-192.png',
  'apple-touch-icon.png',
  ...listFiles('_expo/static/js/web').filter((f) => f.endsWith('.js')),
  ...listFiles('_expo/static/css').filter((f) => f.endsWith('.css')),
].filter((f) => f === '' || fs.existsSync(path.join(DIST, f)));

const sw = `// Generated by scripts/generate-sw.js. Do not edit.
const BUILD_ID = ${JSON.stringify(buildId)};
const CACHE = 'listful-' + BUILD_ID;
const SCOPE = self.registration.scope;
const PRECACHE = ${JSON.stringify(precache, null, 2)}.map((p) => new URL(p, SCOPE).href);

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(
        keys.filter((k) => k.startsWith('listful-') && k !== CACHE).map((k) => caches.delete(k)),
      ))
      .then(() => self.clients.claim()),
  );
});

async function networkFirst(request) {
  const cache = await caches.open(CACHE);
  try {
    const response = await fetch(request);
    if (response.ok) cache.put(request, response.clone());
    return response;
  } catch (err) {
    return (await cache.match(request, { ignoreSearch: true })) || (await cache.match(SCOPE)) || Response.error();
  }
}

async function cacheFirst(request) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(request);
  if (cached) return cached;
  const response = await fetch(request);
  if (response.ok) cache.put(request, response.clone());
  return response;
}

async function staleWhileRevalidate(request, event) {
  const cache = await caches.open(CACHE);
  const cached = await cache.match(request);
  const refresh = fetch(request)
    .then((response) => {
      if (response.ok) cache.put(request, response.clone());
      return response;
    })
    .catch(() => cached || Response.error());
  if (cached) {
    event.waitUntil(refresh);
    return cached;
  }
  return refresh;
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || !request.url.startsWith(SCOPE)) return;
  const path = request.url.slice(SCOPE.length);
  if (path === 'sw.js') return;

  if (request.mode === 'navigate') {
    event.respondWith(networkFirst(request));
  } else if (path.startsWith('_expo/static/') || path.startsWith('assets/')) {
    event.respondWith(cacheFirst(request));
  } else {
    event.respondWith(staleWhileRevalidate(request, event));
  }
});
`;

fs.writeFileSync(path.join(DIST, 'sw.js'), sw);
console.log(`dist/sw.js written (build ${buildId}, ${precache.length} precached files)`);
